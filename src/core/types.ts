// Domain types shared by every runtime (Cloudflare Workers / AWS Lambda / local).
// GitHub numeric IDs are the canonical identifiers; logins/slugs are display-only
// because they can be renamed and re-registered by someone else.

export type GitHubId = number;

export interface User {
  id: GitHubId;
  login: string;
  name: string | null;
  avatarUrl: string | null;
  createdAt: string;
  updatedAt: string;
}

/** Org / team memberships of a user, as reported by GitHub. */
export interface Memberships {
  orgIds: GitHubId[];
  teamIds: GitHubId[];
}

export type StorageProviderKind = 'r2' | 's3' | 'local';
export type Visibility = 'public' | 'private';
export type VerifyStatus = 'unverified' | 'verified' | 'failed';

export interface R2Config {
  provider: 'r2';
  accountId: string;
  bucket: string;
}

export interface S3Config {
  provider: 's3';
  region: string;
  bucket: string;
  roleArn: string;
  /** Generated by the registry, never chosen by the user (confused-deputy protection). */
  externalId: string;
}

/** Local development only (SeaweedFS). The endpoint comes from server config, never from users. */
export interface LocalConfig {
  provider: 'local';
  bucket: string;
}

export type StorageConfig = R2Config | S3Config | LocalConfig;

export interface Bucket {
  id: string;
  ownerId: GitHubId;
  name: string;
  description: string;
  visibility: Visibility;
  storage: StorageConfig;
  /** Encrypted static credential envelope (R2 / local). Never leaves the server. */
  credentialCiphertext: string | null;
  verifyStatus: VerifyStatus;
  verifyDetail: string | null;
  verifiedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

export type PrincipalType = 'user' | 'org' | 'team';

export interface AclEntry {
  type: PrincipalType;
  /** GitHub numeric ID of the user / org / team. */
  id: GitHubId;
  /** Display name at the time the entry was written (login, org login, or org/team-slug). */
  name: string;
}

/** Plaintext static credentials. Only exists in memory inside CredentialResolver/StorageProvider. */
export interface StaticCredentials {
  accessKeyId: string;
  secretAccessKey: string;
}

export interface ResolvedCredentials extends StaticCredentials {
  sessionToken?: string;
  /** Epoch ms; undefined for long-lived keys. */
  expiresAt?: number;
}

export interface Session {
  idHash: string;
  userId: GitHubId;
  /** Encrypted GitHub OAuth access token. */
  tokenCiphertext: string;
  csrfToken: string;
  expiresAt: number;
  createdAt: number;
}

export interface AuditEvent {
  ts: string;
  actorId: GitHubId | null;
  action: string;
  bucketId: string | null;
  outcome: 'allow' | 'deny' | 'error' | 'ok';
  detail?: Record<string, unknown>;
}
